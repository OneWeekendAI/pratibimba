// The instruction pack: files that teach a coding agent to read Pratibimba and submit drafts.
//
// Two kinds of file, two rules:
// - Pack files (the skill, the Cursor rule, the generic instructions) are ours. Absent: write.
//   Identical: leave. Different: the developer edited it, so keep it unless `force`.
// - MCP configs (`.mcp.json`, `.cursor/mcp.json`) are shared with other servers. We only ever
//   touch `mcpServers.pratibimba`; every other key stays as it was. A file we cannot parse is
//   left alone and reported as an error.
//
// The token itself is never written: configs reference an environment variable.

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isDeepStrictEqual } from 'node:util';

const here = dirname(fileURLToPath(import.meta.url));
export const SERVER_NAME = 'pratibimba';
export const DEFAULT_TOKEN_ENV = 'PRATIBIMBA_MCP_TOKEN';
export const DEFAULT_URL = 'http://localhost:8080/mcp';

export async function packVersion() {
  return JSON.parse(await readFile(join(here, '..', 'package.json'), 'utf8')).version;
}

/** Core's base URL or its /mcp URL, normalised to the /mcp URL. */
export function mcpUrl(raw) {
  let u;
  try {
    u = new URL(raw);
  } catch {
    throw new Error(`not a URL: ${raw}`);
  }
  if (u.protocol !== 'http:' && u.protocol !== 'https:') throw new Error(`the MCP URL must be http or https: ${raw}`);
  if (u.username || u.password) throw new Error('put the token in the environment, not in the URL');
  u.search = '';
  u.hash = '';
  const path = u.pathname.replace(/\/+$/, '');
  u.pathname = path.endsWith('/mcp') ? path : `${path}/mcp`;
  return u.toString();
}

export function checkEnvName(name) {
  if (!/^[A-Z_][A-Z0-9_]*$/.test(name)) throw new Error(`not an environment variable name: ${name}`);
  return name;
}

/** The `mcpServers.pratibimba` entry each config gets. */
export function serverEntries(url, tokenEnv) {
  return {
    // Claude Code expands ${VAR} in .mcp.json.
    claude: { type: 'http', url, headers: { Authorization: `Bearer \${${tokenEnv}}` } },
    // Cursor expands ${env:VAR} in mcp.json.
    cursor: { url, headers: { Authorization: `Bearer \${env:${tokenEnv}}` } },
    generic: { type: 'http', url, headers: { Authorization: `Bearer \${${tokenEnv}}` } },
  };
}

function fill(text, vars) {
  return text.replace(/\{\{(\w+)\}\}/g, (m, k) => (k in vars ? vars[k] : m));
}

export async function packFiles({ url, tokenEnv }) {
  const version = await packVersion();
  const guide = fill(await readFile(join(here, '..', 'pack', 'guide.md'), 'utf8'), { MCP_URL: url, TOKEN_ENV: tokenEnv });
  const stamp = `<!-- pratibimba-pack ${version}. Generated by \`npx @pratibimba/agent install\`; edit freely, a re-install keeps your edits. -->`;
  const skill = [
    '---',
    'name: pratibimba',
    'description: Use when the user wants new or better variants for a Pratibimba slot (a <prb.Slot>, a prb:slot region, a personalised hero or promo), or asks how a slot is performing, which variant wins, or why a visitor saw what they saw. Reads results through the pratibimba MCP server and submits variants as drafts that a person approves.',
    '---',
    stamp,
    '',
    guide,
  ].join('\n');
  const rule = [
    '---',
    'description: Pratibimba personalisation. Apply when writing or changing variants for a Pratibimba slot (<prb.Slot>, prb:slot), or when asked how a slot performs or why a visitor saw a variant.',
    'globs:',
    'alwaysApply: false',
    '---',
    stamp,
    '',
    guide,
  ].join('\n');
  const generic = [
    stamp,
    '<!-- For any MCP client: add the server in .pratibimba/mcp.json to your client, and give it this file as instructions',
    `     (system prompt, project rules, or AGENTS.md). If your client does not expand \${${tokenEnv}}, paste the token`,
    '     into your client\'s own config, never into a committed file. -->',
    '',
    guide,
  ].join('\n');
  const entries = serverEntries(url, tokenEnv);
  return [
    { path: '.claude/skills/pratibimba/SKILL.md', kind: 'pack', content: skill },
    { path: '.mcp.json', kind: 'config', entry: entries.claude },
    { path: '.cursor/rules/pratibimba.mdc', kind: 'pack', content: rule },
    { path: '.cursor/mcp.json', kind: 'config', entry: entries.cursor },
    { path: '.pratibimba/agent-instructions.md', kind: 'pack', content: generic },
    { path: '.pratibimba/mcp.json', kind: 'config', entry: entries.generic },
  ];
}

async function readOrNull(p) {
  try {
    return await readFile(p, 'utf8');
  } catch (e) {
    if (e.code === 'ENOENT') return null;
    throw e;
  }
}

async function put(p, text) {
  await mkdir(dirname(p), { recursive: true });
  await writeFile(p, text);
}

async function installPack(abs, content, force) {
  const old = await readOrNull(abs);
  if (old === null) {
    await put(abs, content);
    return { action: 'created' };
  }
  if (old === content) return { action: 'unchanged' };
  if (!force) return { action: 'kept', detail: 'differs from the pack (your edits?); --force replaces it' };
  await put(abs, content);
  return { action: 'replaced' };
}

async function installConfig(abs, entry, force) {
  const old = await readOrNull(abs);
  let doc = {};
  if (old !== null && old.trim() !== '') {
    try {
      doc = JSON.parse(old);
    } catch (e) {
      return { action: 'error', detail: `not valid JSON, left untouched (${e.message})` };
    }
    if (doc === null || typeof doc !== 'object' || Array.isArray(doc)) return { action: 'error', detail: 'not a JSON object, left untouched' };
  }
  const servers = doc.mcpServers ?? {};
  if (typeof servers !== 'object' || servers === null || Array.isArray(servers)) {
    return { action: 'error', detail: 'mcpServers is not an object, left untouched' };
  }
  const current = servers[SERVER_NAME];
  if (current !== undefined && isDeepStrictEqual(current, entry)) return { action: 'unchanged' };
  if (current !== undefined && !force) {
    return { action: 'kept', detail: `already has a different "${SERVER_NAME}" server; --force replaces that entry only` };
  }
  doc.mcpServers = { ...servers, [SERVER_NAME]: entry };
  await put(abs, `${JSON.stringify(doc, null, 2)}\n`);
  return { action: old === null ? 'created' : current === undefined ? 'added' : 'replaced' };
}

/**
 * Install the pack into `dir`. Returns one report row per file: `{ path, action, detail? }`,
 * where action is created | added | unchanged | kept | replaced | error.
 */
export async function install({ dir, url = DEFAULT_URL, tokenEnv = DEFAULT_TOKEN_ENV, force = false }) {
  const files = await packFiles({ url: mcpUrl(url), tokenEnv: checkEnvName(tokenEnv) });
  const report = [];
  for (const f of files) {
    const abs = join(dir, f.path);
    const r = f.kind === 'pack' ? await installPack(abs, f.content, force) : await installConfig(abs, f.entry, force);
    report.push({ path: f.path, ...r });
  }
  return report;
}
